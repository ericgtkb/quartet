#!/bin/sh
# Generate Python code for score/*.proto into src/melody/generated/quartet/score/.
# grpcio-tools bundles protoc, so no system protoc is needed.
set -eu

cd "$(dirname "$0")/.."
out=src/melody/generated

rm -rf "$out"
mkdir -p "$out/quartet"
# The proto root is the repository root, so files land in quartet/score/.
uv run --frozen python -m grpc_tools.protoc -I .. \
  --python_out="$out/quartet" --pyi_out="$out/quartet" --grpc_python_out="$out/quartet" \
  ../score/*.proto

# protoc writes imports from the proto *file path* ("from score import x_pb2");
# rewrite them to the package path and make each directory a regular package.
uv run --frozen python - "$out" <<'PY'
import pathlib
import sys

out = pathlib.Path(sys.argv[1])
for path in (out / 'quartet' / 'score').glob('*.py*'):
    text = path.read_text()
    path.write_text(text.replace('from score import ', 'from melody.generated.quartet.score import '))
for pkg in (out, out / 'quartet', out / 'quartet' / 'score'):
    (pkg / '__init__.py').write_text('"""Generated by scripts/gen-proto.sh. Do not edit."""\n')
PY
